export type FieldType =
  | 'text'
  | 'textarea'
  | 'number'
  | 'money'
  | 'percent'
  | 'date'
  | 'month'
  | 'time'
  | 'select'
  | 'ref'
  | 'multiref'
  | 'bool'
  | 'url'
  | 'rating'

export type Field = {
  key: string
  label: string
  type: FieldType
  options?: string[]
  ref?: string // coleção referenciada (ref / multiref)
  required?: boolean
  help?: string
  min?: number
  max?: number
  wide?: boolean // ocupa a linha inteira no formulário
  default?: unknown
}

